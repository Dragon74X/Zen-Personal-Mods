#!/usr/bin/env node
// Builds svg/<style>/<icon>.svg, svg/static/ and Zen-Motion-Icons.html from glyphs.js + motion.js.
// --check verifies coverage, return-to-rest for every icon x style, and that outputs are current.
'use strict';
const fs = require('fs'), path = require('path');
const dir = __dirname, root = path.join(dir, '..', '..'), check = process.argv.includes('--check');
require('./glyphs.js'); require('./motion.js');
const { list, actions, byId } = globalThis.ZenGlyphs, { compile, markup, sample, STYLES } = globalThis.ZenMotion;
const fail = [];

// Every Iconflow action ID must have a glyph; window controls stay out of this set.
const morph = JSON.parse(fs.readFileSync(path.join(root, 'iconflow', 'morph.json'), 'utf8'));
for (const id of Object.keys(morph.actions)) if (!byId[actions[id]]) fail.push(`Iconflow action ${id} has no glyph`);
for (const id of Object.values(actions)) if (!byId[id]) fail.push(`action map names missing glyph ${id}`);
for (const g of list) if (/minimi[sz]e|maximi[sz]e|restore-window|window-close/.test(g.id)) fail.push(`window control glyph ${g.id}`);

// One full hover, hold, release, return cycle must settle exactly on the rest pose (the other state for toggles).
const cycle = [[0, 'hover'], [900, 'press'], [1500, 'release'], [2800, 'leave']];
for (const g of list) for (const s of Object.keys(STYLES)) {
  let ch;
  try { ch = compile(g, s); } catch (e) { fail.push(`${g.id}/${s}: ${e.message}`); continue; }
  const [end] = sample(ch, cycle, [7000]), rest = ch.sets[g.toggle ? 1 : 0].parts;
  end.forEach((v, i) => {
    const want = rest[i].P[0], ri = ch.parts[i].n + 2;
    for (let j = 0; j < v.length; j++) {
      const d = j === ri ? ((v[j] - want[j]) % 360 + 540) % 360 - 180 : v[j] - want[j];
      if (!Number.isFinite(v[j]) || Math.abs(d) > .01) { fail.push(`${g.id}/${s}: part ${i} channel ${j} ends at ${v[j]}, rest ${want[j]}`); break; }
    }
  });
}

const out = new Map();
const asset = (g, s, set = 0) => markup(compile(g, s), { set, attrs: ` data-icon="${g.id}" data-style="${s}"` });
for (const s of Object.keys(STYLES)) for (const g of list)
  out.set(`svg/${s}/${g.id}.svg`, asset(g, s).replace(/<\/svg>$/, '<script href="../../glyphs.js"/><script href="../../motion.js"/><script>ZenMotion.autoAttach()</script></svg>') + '\n');
for (const g of list) {
  out.set(`svg/static/${g.id}.svg`, asset(g, 'clean') + '\n');
  if (g.toggle) out.set(`svg/static/${g.id}--on.svg`, asset(g, 'clean', 1) + '\n');
}
const page = fs.readFileSync(path.join(dir, 'page.html'), 'utf8')
  .replace(/<script src="(glyphs|motion)\.js"><\/script>/g, (_, f) => `<script>\n${fs.readFileSync(path.join(dir, f + '.js'), 'utf8')}</script>`);
out.set('Zen-Motion-Icons.html', `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body>\n${page}</body>\n</html>\n`);

if (check) {
  for (const [f, text] of out) { const p = path.join(dir, f); if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text) fail.push(`${f} is stale; run node resources/animated-icons/build.cjs`); }
  const svgs = new Set([...out.keys()].filter(f => f.startsWith('svg/')));
  for (const d of fs.existsSync(path.join(dir, 'svg')) ? fs.readdirSync(path.join(dir, 'svg')) : [])
    for (const f of fs.readdirSync(path.join(dir, 'svg', d))) if (!svgs.has(`svg/${d}/${f}`)) fail.push(`svg/${d}/${f} is not generated by build.cjs`);
} else if (!fail.length) {
  fs.rmSync(path.join(dir, 'svg'), { recursive: true, force: true });
  for (const [f, text] of out) { fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true }); fs.writeFileSync(path.join(dir, f), text); }
}
if (fail.length) { console.error(fail.slice(0, 40).join('\n') + (fail.length > 40 ? `\n... ${fail.length - 40} more` : '')); process.exit(1); }
console.log(`${list.length} glyphs x ${Object.keys(STYLES).length} styles: ${out.size} files ${check ? 'current' : 'written'}; ${Object.keys(morph.actions).length} Iconflow actions covered; every cycle returns to rest.`);
